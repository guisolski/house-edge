/** Uppercase pt-BR accented letters required for neon signs. */
export const PT_BR_ACCENTS = 'ÃÕÇÁÉÍÓÚÂÊÔÀ' as const;

export function hasGlyph(ch: string): boolean {
  const key = ch.toUpperCase();
  return Object.prototype.hasOwnProperty.call(GLYPHS, key);
}

/** True when every non-space character in `text` has a bitmap glyph. */
export function fontCoversText(text: string): boolean {
  for (const ch of text) {
    if (ch === '\n' || ch === '\r' || ch === '\t') continue;
    if (!hasGlyph(ch)) return false;
  }
  return true;
}

export function measurePixelText(text: string): { w: number; h: number } {
  const chars = text.toUpperCase();
  const w = chars.length === 0 ? 0 : chars.length * (GLYPH_W + GAP) - GAP;
  return { w, h: GLYPH_H };
}

function blitGlyphRow(
  ctx: CanvasRenderingContext2D,
  bits: number,
  ox: number,
  oy: number,
): void {
  for (let col = 0; col < GLYPH_W; col += 1) {
    if (bits & (1 << (GLYPH_W - 1 - col))) ctx.fillRect(ox + col, oy, 1, 1);
  }
}

function blitGlyph(
  ctx: CanvasRenderingContext2D,
  rows: number[],
  ox: number,
  oy: number,
): void {
  for (let row = 0; row < GLYPH_H; row += 1) {
    blitGlyphRow(ctx, rows[row] ?? 0, ox, oy + row);
  }
}

/** Draw label into ctx at integer coords; 1 canvas pixel = 1 font pixel. */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
): void {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    blitGlyph(ctx, GLYPHS[ch] ?? GLYPHS[' ']!, cx, y);
    cx += GLYPH_W + GAP;
  }
}
